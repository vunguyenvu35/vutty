#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md: the licence text of every Go module compiled into the app (for macOS, Windows and
// Linux) and of every npm package the web UI ships (production dependencies only), plus the Go standard library.
// MIT, BSD and Apache-2.0 ask for these notices to travel with the binaries: the release files carry this file.
// Usage: node scripts/notices.mjs        (needs Go, and `npm ci` done in frontend/)
import {execFileSync} from 'node:child_process'
import {existsSync, readdirSync, readFileSync, writeFileSync} from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const run = (cmd, args, env = {}) => execFileSync(cmd, args, {cwd: root, env: {...process.env, ...env}, encoding: 'utf8', maxBuffer: 64 << 20})
const LICENSE_FILE = /^(licen[sc]e|copying|notice|unlicense)([-_.].*)?$/i

function licenceFiles(dir) {
  if (!dir || !existsSync(dir)) return []
  return readdirSync(dir, {withFileTypes: true}).filter(e => e.isFile() && LICENSE_FILE.test(e.name)).map(e => e.name).sort()
}

function kind(text) {
  const t = text.slice(0, 4000)
  if (/Apache License/i.test(t) && /Version 2\.0/.test(t)) return 'Apache-2.0'
  if (/Mozilla Public License/i.test(t)) return 'MPL-2.0'
  if (/Permission is hereby granted, free of charge/i.test(t)) return 'MIT'
  if (/Redistribution and use in source and binary forms/i.test(t)) return /Neither the name|may be used to endorse/i.test(t) ? 'BSD-3-Clause' : 'BSD-2-Clause'
  if (/Permission to use, copy, modify, and\/or distribute/i.test(t)) return 'ISC'
  if (/This is free and unencumbered software/i.test(t)) return 'Unlicense'
  return 'see text'
}

// --- Go: the modules that are really linked in, per target system
const goMods = new Map()
for (const goos of ['darwin', 'linux', 'windows']) {
  const out = run('go', ['list', '-deps', '-tags', 'desktop,production', '-f', '{{with .Module}}{{if not .Main}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}', '.'], {GOOS: goos, GOARCH: 'amd64', CGO_ENABLED: '1'})
  for (const line of out.split('\n')) {
    const [mod, version, dir] = line.split('\t')
    if (!mod) continue
    const e = goMods.get(mod) ?? {mod, version, dir, os: new Set()}
    e.os.add(goos)
    goMods.set(mod, e)
  }
}
const goroot = run('go', ['env', 'GOROOT']).trim()
const entries = [{name: 'Go standard library', version: run('go', ['env', 'GOVERSION']).trim(), files: [[path.join(goroot, 'LICENSE'), 'LICENSE']], group: 'Go'}]
for (const e of [...goMods.values()].sort((a, b) => a.mod.localeCompare(b.mod))) {
  entries.push({name: e.mod, version: e.version, files: licenceFiles(e.dir).map(f => [path.join(e.dir, f), f]), group: 'Go'})
}

// --- npm: the closure of "dependencies" (what vite bundles), not the dev tools
const fe = path.join(root, 'frontend')
const seen = new Set()
function walk(name, from) {
  let dir = from
  for (;;) {
    const p = path.join(dir, 'node_modules', name)
    if (existsSync(path.join(p, 'package.json'))) { visit(p); return }
    const up = path.dirname(dir)
    if (up === dir) throw new Error(`package ${name} not found: run npm ci in frontend/`)
    dir = up
  }
}
function visit(p) {
  if (seen.has(p)) return
  seen.add(p)
  const pkg = JSON.parse(readFileSync(path.join(p, 'package.json'), 'utf8'))
  for (const d of Object.keys(pkg.dependencies ?? {})) walk(d, p)
}
for (const d of Object.keys(JSON.parse(readFileSync(path.join(fe, 'package.json'), 'utf8')).dependencies ?? {})) walk(d, fe)
for (const p of [...seen].sort()) {
  const pkg = JSON.parse(readFileSync(path.join(p, 'package.json'), 'utf8'))
  entries.push({name: pkg.name, version: pkg.version, declared: typeof pkg.license === 'string' ? pkg.license : pkg.license?.type, files: licenceFiles(p).map(f => [path.join(p, f), f]), group: 'npm'})
}

// --- write
const missing = entries.filter(e => e.files.length === 0).map(e => `${e.group}: ${e.name}`)
if (missing.length) { console.error('no licence file found for:\n  ' + missing.join('\n  ')); process.exit(1) }

let md = `# Third-party notices

Vutty itself is released under the MIT licence (see \`LICENSE\`). It includes the open-source software listed below, each under its own licence. This file is generated by \`scripts/notices.mjs\` (run \`make notices\`); the modules listed are the ones compiled into the macOS, Windows and Linux builds, and the npm packages bundled into the user interface.

`
for (const group of ['Go', 'npm']) {
  const list = entries.filter(e => e.group === group)
  md += `## ${group === 'Go' ? 'Go modules' : 'npm packages (user interface)'}\n\n| Package | Version | Licence |\n| --- | --- | --- |\n`
  for (const e of list) {
    const texts = e.files.map(([p]) => readFileSync(p, 'utf8'))
    const k = [...new Set(texts.map(kind).filter(x => x !== 'see text'))].join(' / ') || e.declared || 'see text'
    e.kind = k
    md += `| ${e.name} | ${e.version} | ${k} |\n`
  }
  md += '\n'
}
md += '## Licence texts\n\n'
for (const e of entries) {
  md += `### ${e.name} ${e.version}\n\n`
  for (const [p, f] of e.files) md += `${e.files.length > 1 ? `**${f}**\n\n` : ''}\`\`\`text\n${readFileSync(p, 'utf8').trim()}\n\`\`\`\n\n`
}
writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), md)
const counts = {}
for (const e of entries) counts[e.kind] = (counts[e.kind] ?? 0) + 1
console.log(`THIRD_PARTY_NOTICES.md: ${entries.length} components`, counts)
